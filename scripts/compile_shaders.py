#!/usr/bin/env python3
"""scripts/compile_shaders.py — compile GLSL → SPIR-V → C header.

Used by GitHub Actions to regenerate `app/src/main/cpp/poseidon2b_spirv.h`
whenever `vulkan/shaders/poseidon2b.comp` changes. Locally can be run
manually after installing `glslangValidator` (or `glslc`).

Usage: python3 scripts/compile_shaders.py
"""

from __future__ import annotations
import os, sys, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADER = ROOT / "vulkan" / "shaders" / "poseidon2b.comp"
HEADER = ROOT / "app" / "src" / "main" / "cpp" / "poseidon2b_spirv.h"

# Try glslangValidator first, fall back to glslc
def find_compiler() -> str:
    for c in ("glslangValidator", "glslc"):
        try:
            subprocess.run([c, "--version"], capture_output=True, check=True)
            return c
        except (FileNotFoundError, subprocess.CalledProcessError):
            continue
    raise RuntimeError("No GLSL compiler found. Install glslang or shaderc.")


def main() -> int:
    if not SHADER.exists():
        print(f"WARN: {SHADER} does not exist; using placeholder SPIR-V.")
        return 0

    compiler = find_compiler()
    tmp_spirv = SHADER.with_suffix(".spv")
    subprocess.run(
        [compiler, "-V", "--quiet", "-o", str(tmp_spirv), str(SHADER)],
        check=True,
    )
    data = tmp_spirv.read_bytes()

    with HEADER.open("w") as f:
        f.write("// Auto-generated by scripts/compile_shaders.py — do not edit.\n")
        f.write(f"// Source: vulkan/shaders/poseidon2b.comp\n")
        f.write("// Size: {len(data)} bytes\n\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("static const unsigned char kPoseidon2bSpirv[] = {\n")
        for i, b in enumerate(data):
            if i % 12 == 0: f.write("    ")
            f.write(f"0x{b:02x}, ")
            if i % 12 == 11: f.write("\n")
        f.write("\n};\n")
        f.write(f"static constexpr unsigned kPoseidon2bSpirvLen = sizeof(kPoseidon2bSpirv);\n")

    tmp_spirv.unlink(missing_ok=True)
    print(f"OK: wrote {HEADER} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
